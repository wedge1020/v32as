//
// buildscript.c: the ROM definition for packrom, and Make.sh / Make.bat that rebuild the cartridge
//
// The scripts are written next to the first source (or in its parent for a src/ + obj/ layout), the way v32cc
// writes them, and rebuild the program from there on: the assembler is told what to do with the same options, the
// images and sounds named by %texture / %sound are converted with png2vircon / wav2vircon, and packrom packs the
// cartridge.  When v32opt is on the PATH when a script runs, the optimizer runs first and a second cartridge,
// bin/NAMEOpt.v32, is built from its output; that part can fail without failing the build.
//
// Three things keep a script from being replaced while it runs, or a hand-written one from being replaced at all:
//   * a script carries a "Generated by v32as" line; a file without it is never touched
//   * the scripts call v32as with --no-build-scripts and set V32AS_BUILD_SCRIPT, which v32as honours the same way
//   * a script that has to change is written to a temporary file and renamed over the old one, so a shell that is
//     reading the old one keeps its copy (cmd.exe reads by position: the first two points are what protect it)
//
////////////////////////////////////////////////////////////////////////////////////////

