#define MARKER  "Generated by v32as"

#ifdef _WIN32
#define IS_SEP(c)  ((c) == '/' || (c) == '\\')
#else
#define IS_SEP(c)  ((c) == '/')
#endif

////////////////////////////////////////////////////////////////////////////////////////
//
// Small helpers: a growing string, a list of strings
//
typedef struct { char  *s;  size_t n, cap; }  sb_t;
typedef struct { char **v;  int n, cap; }     sv_t;

static void  *xalloc (size_t n)
{
    void  *p = malloc (n ? n : 1);

    if (p == NULL)
    {
        fprintf (stderr, "v32as: out of memory\n");
        exit (2);
    }

    return (p);
}

static char  *xdup (const char *s)
{
    size_t  n = strlen (s);
    char   *p = xalloc (n + 1);

    memcpy (p, s, n + 1);

    return (p);
}

static void  sb_put (sb_t *b, const char *s, size_t n)
{
    if (b -> n + n + 1 > b -> cap)
    {
        b -> cap = (b -> n + n + 1) * 2;
        b -> s   = realloc (b -> s, b -> cap);

        if (b -> s == NULL)
        {
            fprintf (stderr, "v32as: out of memory\n");
            exit (2);
        }
    }

    memcpy (b -> s + b -> n, s, n);
    b -> n += n;
    b -> s[b -> n] = 0;
}

static void  sb_puts (sb_t *b, const char *s)  { sb_put (b, s, strlen (s)); }
static void  sb_putc (sb_t *b, char c)         { sb_put (b, &c, 1); }

static void  sb_printf (sb_t *b, const char *fmt, ...)
{
    char     tmp[1024];
    va_list  ap;
    int      n;

    va_start (ap, fmt);
    n = vsnprintf (tmp, sizeof (tmp), fmt, ap);
    va_end (ap);

    if (n >= (int) sizeof (tmp))                    // a long name: do it again at its size
    {
        char  *big = xalloc ((size_t) n + 1);

        va_start (ap, fmt);
        vsnprintf (big, (size_t) n + 1, fmt, ap);
        va_end (ap);
        sb_put (b, big, (size_t) n);
        free (big);
    }
    else if (n > 0)
    {
        sb_put (b, tmp, (size_t) n);
    }
}

static char  *sb_take (sb_t *b)
{
    char  *s = b -> s ? b -> s : xdup ("");

    b -> s = NULL;
    b -> n = b -> cap = 0;

    return (s);
}

static void  sv_add (sv_t *v, const char *s)
{
    if (v -> n == v -> cap)
    {
        v -> cap = v -> cap ? v -> cap * 2 : 8;
        v -> v   = realloc (v -> v, (size_t) v -> cap * sizeof (char *));

        if (v -> v == NULL)
        {
            fprintf (stderr, "v32as: out of memory\n");
            exit (2);
        }
    }

    v -> v[v -> n++] = xdup (s);
}

static int  sv_has (const sv_t *v, const char *s)
{
    int  i;

    for (i = 0; i < v -> n; i++)
    {
        if (strcmp (v -> v[i], s) == 0)
        {
            return (1);
        }
    }

    return (0);
}

// (file names that differ only in case are one file on Windows and macOS)
static int  sv_has_ci (const sv_t *v, const char *s)
{
    int  i;

    for (i = 0; i < v -> n; i++)
    {
        if (strcasecmp (v -> v[i], s) == 0)
        {
            return (1);
        }
    }

    return (0);
}

static void  sv_free (sv_t *v)
{
    int  i;

    for (i = 0; i < v -> n; i++)
    {
        free (v -> v[i]);
    }

    free (v -> v);
    v -> v = NULL;
    v -> n = v -> cap = 0;
}

void  bs_args_add (bs_args_t *a, const char *text, int is_path)
{
    if (a -> n == a -> cap)
    {
        a -> cap  = a -> cap ? a -> cap * 2 : 16;
        a -> text = realloc (a -> text, (size_t) a -> cap * sizeof (char *));
        a -> path = realloc (a -> path, (size_t) a -> cap * sizeof (int));

        if (a -> text == NULL || a -> path == NULL)
        {
            fprintf (stderr, "v32as: out of memory\n");
            exit (2);
        }
    }

    a -> text[a -> n] = xdup (text);
    a -> path[a -> n] = is_path;
    a -> n++;
}

void  bs_args_free (bs_args_t *a)
{
    int  i;

    for (i = 0; i < a -> n; i++)
    {
        free (a -> text[i]);
    }

    free (a -> text);
    free (a -> path);
    memset (a, 0, sizeof (*a));
}

////////////////////////////////////////////////////////////////////////////////////////
//
// Paths: made absolute and normalized by text alone (the files need not exist), and written relative to a directory
//
static int  ends_with_ci (const char *s, const char *suffix)
{
    size_t  n = strlen (s);
    size_t  m = strlen (suffix);

    return (n >= m && strcasecmp (s + n - m, suffix) == 0);
}

static int  is_absolute (const char *p)
{
#ifdef _WIN32
    return (IS_SEP (p[0]) || (isalpha ((unsigned char) p[0]) && p[1] == ':'));
#else
    return (p[0] == '/');
#endif
}

// The last component
static const char  *base_name (const char *p)
{
    const char  *b = p;

    for (; *p; p++)
    {
        if (IS_SEP (*p) && p[1])
        {
            b = p + 1;
        }
    }

    return (b);
}

// The part before the last component ("." when there is none)
static char  *dir_name (const char *p)
{
    const char  *b = base_name (p);
    char        *d;
    size_t       n = (size_t) (b - p);

    while (n > 1 && IS_SEP (p[n - 1]))
    {
        n--;
    }

    if (n == 0)
    {
        return (xdup ("."));
    }

    d = xalloc (n + 1);
    memcpy (d, p, n);
    d[n] = 0;

    return (d);
}

// P without the extension of its last component
static char  *strip_ext (const char *p)
{
    char        *r = xdup (p);
    char        *dot = strrchr (r, '.');
    const char  *b = base_name (r);

    if (dot != NULL && dot > b)
    {
        *dot = 0;
    }

    return (r);
}

// An absolute, normalized path with '/' separators: "." and ".." and doubled separators resolved by text
static char  *path_absolute (const char *p)
{
    sb_t   full = { 0 };
    sv_t   part = { 0 };
    sb_t   out  = { 0 };
    char   cwd[4096];
    size_t i, start = 0;
    char  *c;
    int    k;

    if (!is_absolute (p))
    {
        if (getcwd (cwd, sizeof (cwd)) == NULL)
        {
            strcpy (cwd, ".");
        }

        sb_puts (&full, cwd);
        sb_putc (&full, '/');
    }

    sb_puts (&full, p);
    c = full.s;

    for (i = 0; c[i]; i++)
    {
        if (c[i] == '\\' && IS_SEP ('\\'))
        {
            c[i] = '/';
        }
    }

#ifdef _WIN32
    if (isalpha ((unsigned char) c[0]) && c[1] == ':')          // keep the drive as the root
    {
        sb_put (&out, c, 2);
        start = 2;
    }
#endif

    for (i = start; ; )
    {
        size_t  e;
        char    save;

        while (c[i] == '/')
        {
            i++;
        }

        if (c[i] == 0)
        {
            break;
        }

        for (e = i; c[e] && c[e] != '/'; e++)
        {
        }

        save = c[e];
        c[e] = 0;

        if (strcmp (c + i, ".") == 0)
        {
        }
        else if (strcmp (c + i, "..") == 0)
        {
            if (part.n > 0)
            {
                free (part.v[--part.n]);
            }
        }
        else
        {
            sv_add (&part, c + i);
        }

        c[e] = save;
        i    = e;
    }

    for (k = 0; k < part.n; k++)
    {
        sb_putc (&out, '/');
        sb_puts (&out, part.v[k]);
    }

    if (out.n == 0 || (out.n == 2 && out.s[1] == ':'))
    {
        sb_putc (&out, '/');
    }

    sv_free (&part);
    free (full.s);

    return (sb_take (&out));
}

// TARGET as seen from the directory BASE (both absolute and normalized); TARGET itself when they share no root
static char  *path_relative (const char *base, const char *target)
{
    sb_t    out = { 0 };
    size_t  i = 0, common = 0;
    const char  *rest;

    // the longest common run of whole components
    while (base[i] && target[i] && base[i] == target[i])
    {
        if (base[i] == '/')
        {
            common = i + 1;
        }

        i++;
    }

    if (base[i] == 0 && (target[i] == '/' || target[i] == 0))   // BASE is TARGET or a parent of it
    {
        common = i + (target[i] == '/');
    }
    else if (target[i] == 0 && base[i] == '/')                  // TARGET is a parent of BASE
    {
        common = i + 1;
    }

#ifdef _WIN32
    if (common == 0)                                            // another drive: no way to be relative
    {
        return (xdup (target));
    }
#endif

    // (when one path ends where the other has a '/', COMMON counts that '/' and may be one past the end)
    rest = base + (common > strlen (base) ? strlen (base) : common);

    while (*rest)
    {
        if (*rest == '/')
        {
            rest++;
            continue;
        }

        sb_puts (&out, "../");

        while (*rest && *rest != '/')
        {
            rest++;
        }
    }

    sb_puts (&out, target + (common > strlen (target) ? strlen (target) : common));

    if (out.n == 0)
    {
        free (out.s);                                           // (an empty string may still have made a buffer)

        return (xdup ("."));
    }

    if (out.s[out.n - 1] == '/')                                // "../" alone: without the slash
    {
        out.s[--out.n] = 0;
    }

    return (sb_take (&out));
}

// P (as typed) as a path relative to the directory DIR (absolute)
static char  *rel_to (const char *dir, const char *p)
{
    char  *abs = path_absolute (p);
    char  *r   = path_relative (dir, abs);

    free (abs);

    return (r);
}

static char  *join2 (const char *dir, const char *name)
{
    sb_t  b = { 0 };

    if (strcmp (dir, ".") != 0 && dir[0] != 0)
    {
        sb_puts (&b, dir);

        if (!IS_SEP (dir[strlen (dir) - 1]))
        {
            sb_putc (&b, '/');
        }
    }

    sb_puts (&b, name);

    return (sb_take (&b));
}

static int  is_dir (const char *p)
{
    struct stat  st;

    return (stat (p, &st) == 0 && S_ISDIR (st.st_mode));
}

////////////////////////////////////////////////////////////////////////////////////////
//
// The names of a job
//
// OUT = the VBIN.  The optimized twin of every file inserts "Opt" before the extension: NAME.vbin -> NAMEOpt.vbin,
// NAMEOpt.xml, NAMEOpt.asm (the optimizer's output, beside the VBIN), bin/NAMEOpt.v32.
//
static char  *with_opt (const char *path, const char *new_ext)
{
    char  *stem = strip_ext (path);
    sb_t   b = { 0 };

    sb_puts (&b, stem);
    sb_puts (&b, "Opt");

    if (new_ext != NULL)
    {
        sb_puts (&b, new_ext);
    }
    else
    {
        sb_puts (&b, path + strlen (stem));
    }

    free (stem);

    return (sb_take (&b));
}

// NAME.vbin -> NamePre.asm: the source after the preprocessor (beside the other products)
static char  *pre_name (const char *path)
{
    char  *stem = strip_ext (path);
    char  *r    = xalloc (strlen (stem) + 8);

    sprintf (r, "%sPre.asm", stem);
    free (stem);

    return (r);
}

void  bs_names (const bs_job_t *job, bs_names_t *n)
{
    char  *stem = strip_ext (job -> output);
    int    i;

    memset (n, 0, sizeof (*n));

    if (job -> xml != NULL)
    {
        n -> xml = xdup (job -> xml);
    }
    else
    {
        n -> xml = xalloc (strlen (stem) + 5);
        sprintf (n -> xml, "%s.xml", stem);
    }

    n -> xml_opt  = job -> xml_opt ? xdup (job -> xml_opt) : with_opt (n -> xml, ".xml");
    n -> vbin_opt = with_opt (job -> output, NULL);
    n -> asm_opt  = with_opt (job -> output, ".asm");
    n -> asm_pre  = pre_name (job -> output);
    n -> has_opt  = (job -> inputs -> n == 1);

    // never write over a source, or over the other files of the build
    if (n -> has_opt)
    {
        char  *a = path_absolute (n -> asm_opt);
        char  *b = path_absolute (n -> asm_pre);

        for (i = 0; i < job -> inputs -> n && n -> has_opt; i++)
        {
            char  *in = path_absolute (job -> inputs -> text[i]);

            if (strcmp (in, a) == 0 || strcmp (in, b) == 0)
            {
                n -> has_opt = 0;
            }

            free (in);
        }

        free (a);
        free (b);
    }

    free (stem);
}

void  bs_names_free (bs_names_t *n)
{
    free (n -> xml);
    free (n -> xml_opt);
    free (n -> vbin_opt);
    free (n -> asm_opt);
    free (n -> asm_pre);
    memset (n, 0, sizeof (*n));
}

////////////////////////////////////////////////////////////////////////////////////////
//
// The resources: what packrom is told for each %texture / %sound, and what has to be converted to get it
//
// A .png (texture) or .wav (sound) is converted by png2vircon / wav2vircon to a .vtex / .vsnd file next to the XML,
// named after the image (two with the same base name get _2, _3, ...).  Any other file is used as it is, named by
// its path from the XML.
//
typedef struct
{
    char  *xml_name;                // the path in the definition, from the directory of the XML
    char  *convert_in;              // the file to convert (as the assembler found it), or NULL when none
    char  *convert_out;             // where it goes (with a directory part: the XML's)
}
bs_res_t;

static void  res_free (bs_res_t *r, size_t n)
{
    size_t  i;

    for (i = 0; i < n; i++)
    {
        free (r[i].xml_name);
        free (r[i].convert_in);
        free (r[i].convert_out);
    }

    free (r);
}

static bs_res_t  *res_plan (const pp_t *pp, int sound, const char *xml_dir_abs, const char *xml_dir, size_t *count)
{
    const char  *in_ext  = sound ? ".wav"  : ".png";
    const char  *out_ext = sound ? ".vsnd" : ".vtex";
    size_t       n = pp_rom_resources (pp, sound);
    bs_res_t    *r = xalloc ((n ? n : 1) * sizeof (bs_res_t));
    sv_t         taken = { 0 };
    size_t       i;

    memset (r, 0, (n ? n : 1) * sizeof (bs_res_t));

    for (i = 0; i < n; i++)
    {
        const char  *found = NULL;
        const char  *hint  = pp_rom_resource (pp, sound, i, &found);

        if (ends_with_ci (hint, in_ext))
        {
            const char  *b = base_name (hint);
            size_t       stem = strlen (b) - strlen (in_ext);
            sb_t         name = { 0 };
            int          serial = 1;

            for (;;)
            {
                name.n = 0;

                if (name.s != NULL)
                {
                    name.s[0] = 0;
                }

                sb_put (&name, b, stem);

                if (serial > 1)
                {
                    sb_printf (&name, "_%d", serial);
                }

                sb_puts (&name, out_ext);

                if (!sv_has_ci (&taken, name.s))
                {
                    break;
                }

                serial++;
            }

            r[i].xml_name    = xdup (name.s);
            r[i].convert_in  = xdup (found ? found : hint);
            r[i].convert_out = join2 (xml_dir, name.s);
            free (name.s);
        }
        else if (found != NULL)
        {
            char  *abs = path_absolute (found);

            r[i].xml_name = path_relative (xml_dir_abs, abs);
            free (abs);
        }
        else
        {
            r[i].xml_name = xdup (hint);
        }

        sv_add (&taken, r[i].xml_name);
    }

    sv_free (&taken);
    *count = n;

    return (r);
}

////////////////////////////////////////////////////////////////////////////////////////
//
// The ROM definition
//
static void  xml_attr (FILE *fp, const char *s)
{
    for (; *s; s++)
    {
        switch (*s)
        {
            case '&':   fputs ("&amp;", fp);   break;
            case '<':   fputs ("&lt;", fp);    break;
            case '>':   fputs ("&gt;", fp);    break;
            case '"':   fputs ("&quot;", fp);  break;
            default:    fputc (*s, fp);        break;
        }
    }
}

int  bs_write_xml (const pp_t *pp, const char *xml_path, const char *vbin_path, int bios, int optimized,
                   const char *fallback_title)
{
    char        *xdir_abs = NULL;
    char        *xdir     = dir_name (xml_path);
    char        *tmp      = path_absolute (xml_path);
    char        *vabs     = path_absolute (vbin_path);
    char        *vrel;
    const char  *title    = pp_rom_title (pp) ? pp_rom_title (pp) : fallback_title;
    const char  *version  = pp_rom_version (pp) ? pp_rom_version (pp) : "1.0";
    char         shown[80];
    FILE        *fp;
    int          sound;
    size_t       i;
    int          rc = 0;

    xdir_abs = dir_name (tmp);
    free (tmp);
    vrel = path_relative (xdir_abs, vabs);
    free (vabs);

    if (optimized)                                  // room for " [optimized]": 63 characters in all
    {
        size_t  cut = strlen (title) > 51 ? 51 : strlen (title);

        while (cut > 0 && ((unsigned char) title[cut] & 0xC0) == 0x80)
        {
            cut--;
        }

        snprintf (shown, sizeof (shown), "%.*s [optimized]", (int) cut, title);
        title = shown;
    }

    fp = fopen (xml_path, "w");

    if (fp == NULL)
    {
        fprintf (stderr, "v32as: cannot write '%s': %s\n", xml_path, strerror (errno));
        free (xdir_abs);
        free (xdir);
        free (vrel);
        return (-1);
    }

    fputs ("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"no\" ?>\n<rom-definition version=\"1.0\">\n", fp);
    fprintf (fp, "    <rom type=\"%s\" title=\"", bios ? "bios" : "cartridge");
    xml_attr (fp, title);
    fputs ("\" version=\"", fp);
    xml_attr (fp, version);
    fputs ("\" />\n    <binary path=\"", fp);
    xml_attr (fp, vrel);
    fputs ("\" />\n", fp);

    for (sound = 0; sound < 2; sound++)
    {
        size_t     n;
        bs_res_t  *r = res_plan (pp, sound, xdir_abs, xdir, &n);

        fprintf (fp, "    <%s>\n", sound ? "sounds" : "textures");

        for (i = 0; i < n; i++)
        {
            fprintf (fp, "        <%s path=\"", sound ? "sound" : "texture");
            xml_attr (fp, r[i].xml_name);
            fputs ("\" />\n", fp);
        }

        fprintf (fp, "    </%s>\n", sound ? "sounds" : "textures");
        res_free (r, n);
    }

    fputs ("</rom-definition>\n", fp);

    if (ferror (fp) || fclose (fp) != 0)
    {
        fprintf (stderr, "v32as: error writing '%s'\n", xml_path);
        rc = -1;
    }

    free (xdir_abs);
    free (xdir);
    free (vrel);

    return (rc);
}

////////////////////////////////////////////////////////////////////////////////////////
//
// What a script does, as one description that Make.sh and Make.bat are both written from
//
typedef struct
{
    const char *tool;               // as invoked: the default of the V32AS variable
    int         bios;
    char       *dir;                // absolute: where the scripts go
    char       *vbin, *xml;         // relative to dir
    char       *asm_opt, *asm_pre, *vbin_opt, *xml_opt;
    char       *rom, *rom_opt;      // bin/NAME.v32, bin/NAMEOpt.v32
    int         has_opt;
    bs_args_t   flags;              // as relative to dir
    bs_args_t   inputs;
    bs_args_t   opt_flags;          // the flags of the twin's assembly (a directory for its relative %include added)
    sv_t        dirs;               // directories to create
    sv_t        conv_tool, conv_in, conv_out;
}
plan_t;

static void  add_dir_of (plan_t *pl, const char *file)
{
    char  *d = dir_name (file);

    if (strcmp (d, ".") != 0 && !sv_has (&pl -> dirs, d))
    {
        sv_add (&pl -> dirs, d);
    }

    free (d);
}

// next to the first source, or in its parent for the src/ + obj/ layout (the parent has an obj/, or the output goes to one)
static char  *script_dir (const char *output, const char *source)
{
    char  *src_dir = dir_name (source);
    char  *sdir    = path_absolute (src_dir);
    char  *odir0   = dir_name (output);
    char  *odir    = path_absolute (odir0);
    char  *up      = join2 (sdir, "..");
    char  *parent  = path_absolute (up);
    char  *obj     = join2 (parent, "obj");
    int    layout  = strcmp (base_name (sdir), "src") == 0 && (strcmp (base_name (odir), "obj") == 0 || is_dir (obj));

    free (src_dir);
    free (odir0);
    free (odir);
    free (up);
    free (obj);

    if (layout)
    {
        free (sdir);
        return (parent);
    }

    free (parent);

    return (sdir);
}

static void  plan_free (plan_t *pl)
{
    free (pl -> dir);
    free (pl -> vbin);
    free (pl -> xml);
    free (pl -> asm_opt);
    free (pl -> asm_pre);
    free (pl -> vbin_opt);
    free (pl -> xml_opt);
    free (pl -> rom);
    free (pl -> rom_opt);
    bs_args_free (&pl -> flags);
    bs_args_free (&pl -> inputs);
    bs_args_free (&pl -> opt_flags);
    sv_free (&pl -> dirs);
    sv_free (&pl -> conv_tool);
    sv_free (&pl -> conv_in);
    sv_free (&pl -> conv_out);
}

static void  copy_args (bs_args_t *to, const bs_args_t *from, const char *dir)
{
    int  i;

    for (i = 0; i < from -> n; i++)
    {
        char  *t = from -> path[i] ? rel_to (dir, from -> text[i]) : xdup (from -> text[i]);

        bs_args_add (to, t, from -> path[i]);
        free (t);
    }
}

static void  make_plan (plan_t *pl, const bs_job_t *job)
{
    bs_names_t  nm;
    char       *stem;
    char       *tmp;
    char       *xdir, *xdir_abs;
    int         sound;
    size_t      i;

    memset (pl, 0, sizeof (*pl));
    bs_names (job, &nm);

    pl -> tool    = job -> tool;
    pl -> bios    = job -> bios;
    pl -> has_opt = nm.has_opt;
    pl -> dir     = job -> dir ? path_absolute (job -> dir) : script_dir (job -> output, job -> inputs -> text[0]);
    pl -> vbin    = rel_to (pl -> dir, job -> output);
    pl -> xml     = rel_to (pl -> dir, nm.xml);
    pl -> asm_opt = rel_to (pl -> dir, nm.asm_opt);
    pl -> asm_pre = rel_to (pl -> dir, nm.asm_pre);
    pl -> vbin_opt = rel_to (pl -> dir, nm.vbin_opt);
    pl -> xml_opt = rel_to (pl -> dir, nm.xml_opt);

    stem = strip_ext (base_name (job -> output));
    pl -> rom = xalloc (strlen (stem) + 16);
    sprintf (pl -> rom, "bin/%s.v32", stem);
    pl -> rom_opt = xalloc (strlen (stem) + 16);
    sprintf (pl -> rom_opt, "bin/%sOpt.v32", stem);
    free (stem);

    copy_args (&pl -> flags, job -> flags, pl -> dir);
    copy_args (&pl -> inputs, job -> inputs, pl -> dir);
    copy_args (&pl -> opt_flags, job -> flags, pl -> dir);

    if (pl -> has_opt)
    {
        char  *in_dir = dir_name (pl -> inputs.text[0]);
        char  *op_dir = dir_name (pl -> asm_opt);


        // the twin is assembled from another place than the source: what the source %includes or reads with
        // datafile, relative to itself, is found through its directory
        if (strcmp (in_dir, op_dir) != 0)
        {
            int  k, present = 0;

            for (k = 0; k + 1 < pl -> opt_flags.n; k++)
            {
                present |= (strcmp (pl -> opt_flags.text[k], "-I") == 0 && strcmp (pl -> opt_flags.text[k + 1], in_dir) == 0);
            }

            if (!present)
            {
                bs_args_add (&pl -> opt_flags, "-I", 0);
                bs_args_add (&pl -> opt_flags, in_dir, 1);
            }
        }

        free (in_dir);
        free (op_dir);
    }

    add_dir_of (pl, pl -> vbin);
    add_dir_of (pl, pl -> xml);

    if (pl -> has_opt)
    {
        add_dir_of (pl, pl -> asm_pre);
        add_dir_of (pl, pl -> asm_opt);
        add_dir_of (pl, pl -> xml_opt);
    }

    // the images and sounds, converted next to the XML
    tmp      = path_absolute (nm.xml);
    xdir_abs = dir_name (tmp);
    xdir     = rel_to (pl -> dir, xdir_abs);
    free (tmp);

    for (sound = 0; sound < 2; sound++)
    {
        size_t     n;
        bs_res_t  *r = res_plan (job -> pp, sound, xdir_abs, xdir, &n);

        for (i = 0; i < n; i++)
        {
            if (r[i].convert_in != NULL)
            {
                char  *in = rel_to (pl -> dir, r[i].convert_in);

                sv_add (&pl -> conv_tool, sound ? "WAV2VIRCON" : "PNG2VIRCON");
                sv_add (&pl -> conv_in, in);
                sv_add (&pl -> conv_out, r[i].convert_out);
                add_dir_of (pl, r[i].convert_out);
                free (in);
            }
        }

        res_free (r, n);
    }

    free (xdir);
    free (xdir_abs);
    bs_names_free (&nm);
}

////////////////////////////////////////////////////////////////////////////////////////
//
// Quoting
//
static void  put_sh (sb_t *b, const char *s)
{
    const char  *p;
    int          plain = *s != 0;

    for (p = s; *p; p++)
    {
        if (!isalnum ((unsigned char) *p) && strchr ("_./=:,+-", *p) == NULL)
        {
            plain = 0;
        }
    }

    if (plain)
    {
        sb_puts (b, s);
        return;
    }

    sb_putc (b, '\'');

    for (p = s; *p; p++)
    {
        if (*p == '\'')
        {
            sb_puts (b, "'\\''");
        }
        else
        {
            sb_putc (b, *p);
        }
    }

    sb_putc (b, '\'');
}

static void  put_bat (sb_t *b, const char *s, int is_path)
{
    const char  *p;
    int          plain = *s != 0;

    for (p = s; *p; p++)
    {
        if (strchr (" \t&|<>^%\"()!,;=", *p) != NULL)
        {
            plain = 0;
        }
    }

    if (!plain)
    {
        sb_putc (b, '"');
    }

    for (p = s; *p; p++)
    {
        if (is_path && *p == '/')
        {
            sb_putc (b, '\\');
        }
        else if (*p == '%')
        {
            sb_puts (b, "%%");
        }
        else if (*p == '"')
        {
            sb_puts (b, "\\\"");
        }
        else
        {
            sb_putc (b, *p);
        }
    }

    if (!plain)
    {
        sb_putc (b, '"');
    }
}

// an argument of the assembler, in either dialect (an option is not a path even if it holds a '/')
static void  put_arg (sb_t *b, const char *s, int is_path, int bat)
{
    if (bat)
    {
        put_bat (b, s, is_path);
    }
    else
    {
        put_sh (b, s);
    }
}

////////////////////////////////////////////////////////////////////////////////////////
//
// The two scripts are the same steps; a few small helpers say a step in the dialect at hand
//
typedef struct
{
    sb_t  b;
    int   bat;
}
script_t;

static void  eol (script_t *s)
{
    sb_puts (&s -> b, s -> bat ? "\r\n" : "\n");
}

static void  line (script_t *s, const char *text)
{
    sb_puts (&s -> b, text);
    eol (s);
}

static void  section (script_t *s, const char *title)
{
    eol (s);
    line (s, s -> bat ? "echo." : "echo");
    sb_printf (&s -> b, "echo %s", title);
    eol (s);
    line (s, "echo --------------------------");
}

static void  put_path (script_t *s, const char *p)
{
    put_arg (&s -> b, p, 1, s -> bat);
}

// the V32AS call: flags, inputs, and the extras
static void  assemble_cmd (script_t *s, const plan_t *pl, int twin)
{
    const bs_args_t  *fl = twin ? &pl -> opt_flags : &pl -> flags;
    int               i;

    if (s -> bat)
    {
        sb_puts (&s -> b, "\"%V32AS%\"");
    }
    else
    {
        sb_puts (&s -> b, "\"$V32AS\"");
    }

    sb_puts (&s -> b, pl -> bios ? " -b" : " -c");

    for (i = 0; i < fl -> n; i++)
    {
        sb_putc (&s -> b, ' ');
        put_arg (&s -> b, fl -> text[i], fl -> path[i] && fl -> text[i][0] != '-', s -> bat);
    }

    if (twin)
    {
        sb_putc (&s -> b, ' ');
        put_path (s, pl -> asm_opt);
    }
    else
    {
        for (i = 0; i < pl -> inputs.n; i++)
        {
            sb_putc (&s -> b, ' ');
            put_path (s, pl -> inputs.text[i]);
        }
    }

    sb_puts (&s -> b, " -o ");
    put_path (s, twin ? pl -> vbin_opt : pl -> vbin);

    if (!twin)
    {
        sb_puts (&s -> b, " --rom-xml ");
        put_path (s, pl -> xml);

        if (pl -> has_opt)
        {
            sb_puts (&s -> b, " --rom-xml-opt ");
            put_path (s, pl -> xml_opt);
        }
    }

    sb_puts (&s -> b, " --no-build-scripts");
}

// v32as -E -P: the source with the preprocessor run, which is what the optimizer has to read (it does not know %macro,
// %if or %rep, and would take every branch of them for code that runs in turn).  Not -g or --map: they are for a VBIN.
static void  preprocess_cmd (script_t *s, const plan_t *pl)
{
    int  i;

    sb_puts (&s -> b, s -> bat ? "\"%V32AS%\"" : "\"$V32AS\"");
    sb_puts (&s -> b, pl -> bios ? " -E -P -b" : " -E -P -c");

    for (i = 0; i < pl -> flags.n; i++)
    {
        const char  *t = pl -> flags.text[i];

        if (strncmp (t, "--debug=", 8) == 0)
        {
            continue;
        }

        if (strcmp (t, "--map") == 0)
        {
            i++;
            continue;
        }

        sb_putc (&s -> b, ' ');
        put_arg (&s -> b, t, pl -> flags.path[i] && t[0] != '-', s -> bat);
    }

    for (i = 0; i < pl -> inputs.n; i++)
    {
        sb_putc (&s -> b, ' ');
        put_path (s, pl -> inputs.text[i]);
    }

    sb_puts (&s -> b, " -o ");
    put_path (s, pl -> asm_pre);
    sb_puts (&s -> b, " --no-build-scripts");
}

static void  tool_vars (script_t *s, const plan_t *pl)
{
    static const struct { const char *var, *name; }  all[] =
    {
        { "V32AS", NULL }, { "PACKROM", "packrom" }, { "V32OPT", "v32opt" }, { "V32OPT_FLAGS", "-O3" },
        { "PNG2VIRCON", "png2vircon" }, { "WAV2VIRCON", "wav2vircon" }
    };
    size_t  k;

    for (k = 0; k < sizeof (all) / sizeof (all[0]); k++)
    {
        const char  *name = all[k].name ? all[k].name : pl -> tool;
        int          used = 1;

        if (strcmp (all[k].var, "V32OPT") == 0 || strcmp (all[k].var, "V32OPT_FLAGS") == 0)
        {
            used = pl -> has_opt;
        }
        else if (strcmp (all[k].var, "PNG2VIRCON") == 0 || strcmp (all[k].var, "WAV2VIRCON") == 0)
        {
            int  i;

            used = 0;

            for (i = 0; i < pl -> conv_tool.n; i++)
            {
                used |= (strcmp (pl -> conv_tool.v[i], all[k].var) == 0);
            }
        }

        if (!used)
        {
            continue;
        }

        if (s -> bat)
        {
            sb_printf (&s -> b, "if not defined %s set \"%s=%s\"\r\n", all[k].var, all[k].var, name);
        }
        else
        {
            sb_printf (&s -> b, "%s=\"${%s:-%s}\"\n", all[k].var, all[k].var, name);
        }
    }
}

static void  need_tool (script_t *s, const char *var)
{
    if (s -> bat)
    {
        sb_printf (&s -> b, "where \"%%%s%%\" >nul 2>nul\r\nif errorlevel 1 (\r\n    echo ERROR: %%%s%% is needed to build, but was not found in PATH\r\n"
                            "    goto :failed\r\n)\r\n", var, var);
    }
    else
    {
        sb_printf (&s -> b, "need_tool \"$%s\"\n", var);
    }
}

static void  render_common (script_t *s, const plan_t *pl)
{
    int  i;
    int  seen_png = 0, seen_wav = 0;

    if (s -> bat)
    {
        sb_puts (&s -> b, "@echo off\r\nREM " MARKER ". Edit the sources (or delete this line and keep a hand-written script)\r\n"
                          "REM rather than this file: it is rewritten by v32as --build-scripts.\r\n"
                          "REM Set V32AS, V32OPT, PACKROM, PNG2VIRCON or WAV2VIRCON to use a tool that is not in the PATH,\r\n"
                          "REM and V32OPT_FLAGS (default -O3) to change how v32opt optimizes.\r\n\r\n"
                          "cd /d \"%~dp0\"\r\n"
                          "REM tell any v32as started from here not to rewrite the scripts that are running\r\n"
                          "set " BS_ENV_GUARD "=1\r\n\r\n");
    }
    else
    {
        sb_puts (&s -> b, "#!/bin/bash\n# " MARKER ". Edit the sources (or delete this line and keep a hand-written script)\n"
                          "# rather than this file: it is rewritten by v32as --build-scripts.\n"
                          "# Set V32AS, V32OPT, PACKROM, PNG2VIRCON or WAV2VIRCON to use a tool that is not in the PATH,\n"
                          "# and V32OPT_FLAGS (default -O3) to change how v32opt optimizes.\n\n"
                          "cd -- \"$(dirname -- \"${BASH_SOURCE[0]:-$0}\")\" || exit 1\n"
                          "# tell any v32as started from here not to rewrite the scripts that are running\n"
                          "export " BS_ENV_GUARD "=1\n\n"
                          "abort_build()\n{\n    echo\n    echo BUILD FAILED\n    exit 1\n}\n\n"
                          "need_tool()\n{\n"
                          "    command -v \"$1\" >/dev/null 2>&1 || { echo \"ERROR: $1 is needed to build, but was not found in PATH\"; abort_build; }\n}\n\n");
    }

    tool_vars (s, pl);
    eol (s);
    line (s, s -> bat ? "REM the tools this build needs" : "# the tools this build needs");
    need_tool (s, "V32AS");
    need_tool (s, "PACKROM");

    for (i = 0; i < pl -> conv_tool.n; i++)
    {
        int  png = strcmp (pl -> conv_tool.v[i], "PNG2VIRCON") == 0;

        if (png ? !seen_png : !seen_wav)
        {
            need_tool (s, pl -> conv_tool.v[i]);
        }

        seen_png |= png;
        seen_wav |= !png;
    }

    if (pl -> has_opt)
    {
        eol (s);

        if (s -> bat)
        {
            sb_puts (&s -> b, "REM the optimizer is optional: without it (or with NO_OPT set) only the regular cartridge is built\r\n"
                              "set HAVE_OPT=0\r\nset OPT_OK=0\r\n"
                              "if not defined NO_OPT (\r\n    where \"%V32OPT%\" >nul 2>nul\r\n    if not errorlevel 1 set HAVE_OPT=1\r\n)\r\n"
                              "if \"%HAVE_OPT%\"==\"0\" echo note: v32opt not used -- skipping the optimized Opt build\r\n");
        }
        else
        {
            sb_puts (&s -> b, "# the optimizer is optional: without it (or with NO_OPT set) only the regular cartridge is built\n"
                              "HAVE_OPT=0\nOPT_OK=0\n"
                              "if [ -z \"$NO_OPT\" ] && command -v \"$V32OPT\" >/dev/null 2>&1; then\n    HAVE_OPT=1\nelse\n"
                              "    echo \"note: v32opt not used -- skipping the optimized (Opt) build\"\nfi\n");
        }
    }

    eol (s);
    line (s, s -> bat ? "REM create the output folders, since the development tools will not" : "# create the output folders, since the development tools will not");

    if (s -> bat)
    {
        sb_puts (&s -> b, "if not exist bin mkdir bin\r\n");
    }
    else
    {
        sb_puts (&s -> b, "mkdir -p bin || abort_build\n");
    }

    for (i = 0; i < pl -> dirs.n; i++)
    {
        if (s -> bat)
        {
            sb_puts (&s -> b, "if not exist ");
            put_bat (&s -> b, pl -> dirs.v[i], 1);
            sb_puts (&s -> b, " mkdir ");
            put_bat (&s -> b, pl -> dirs.v[i], 1);
            sb_puts (&s -> b, "\r\n");
        }
        else
        {
            sb_puts (&s -> b, "mkdir -p ");
            put_sh (&s -> b, pl -> dirs.v[i]);
            sb_puts (&s -> b, " || abort_build\n");
        }
    }
}

static char  *render_sh (const plan_t *pl)
{
    script_t  s = { { 0 }, 0 };
    int       i;

    render_common (&s, pl);

    if (pl -> has_opt)
    {
        section (&s, "Optimize the ASM code");
        sb_puts (&s.b, "if [ \"$HAVE_OPT\" = 1 ]; then\n    if ");
        preprocess_cmd (&s, pl);
        sb_puts (&s.b, " && \"$V32OPT\" $V32OPT_FLAGS ");
        put_sh (&s.b, pl -> asm_pre);
        sb_puts (&s.b, " -o ");
        put_sh (&s.b, pl -> asm_opt);
        sb_puts (&s.b, "; then\n        OPT_OK=1\n    else\n        echo \"warning: v32opt failed -- skipping the optimized (Opt) build\"\n    fi\nfi\n");
    }

    section (&s, "Assemble the ASM code");
    assemble_cmd (&s, pl, 0);
    sb_puts (&s.b, " || abort_build\n");

    if (pl -> has_opt)
    {
        sb_puts (&s.b, "if [ \"$OPT_OK\" = 1 ]; then\n    ");
        assemble_cmd (&s, pl, 1);
        sb_puts (&s.b, " || { echo \"warning: the optimized code did not assemble -- skipping the optimized (Opt) build\"; OPT_OK=0; }\nfi\n");
    }

    if (pl -> conv_in.n)
    {
        section (&s, "Convert the textures and sounds");

        for (i = 0; i < pl -> conv_in.n; i++)
        {
            sb_printf (&s.b, "\"$%s\" ", pl -> conv_tool.v[i]);
            put_sh (&s.b, pl -> conv_in.v[i]);
            sb_puts (&s.b, " -o ");
            put_sh (&s.b, pl -> conv_out.v[i]);
            sb_puts (&s.b, " || abort_build\n");
        }
    }

    section (&s, "Pack the ROM");
    sb_puts (&s.b, "\"$PACKROM\" ");
    put_sh (&s.b, pl -> xml);
    sb_puts (&s.b, " -o ");
    put_sh (&s.b, pl -> rom);
    sb_puts (&s.b, " || abort_build\n");

    if (pl -> has_opt)
    {
        sb_puts (&s.b, "if [ \"$OPT_OK\" = 1 ]; then\n    \"$PACKROM\" ");
        put_sh (&s.b, pl -> xml_opt);
        sb_puts (&s.b, " -o ");
        put_sh (&s.b, pl -> rom_opt);
        sb_puts (&s.b, " || echo \"warning: the optimized (Opt) cartridge could not be packed\"\nfi\n");
    }

    sb_puts (&s.b, "\necho\necho BUILD SUCCESSFUL\n");

    return (sb_take (&s.b));
}

static char  *render_bat (const plan_t *pl)
{
    script_t  s = { { 0 }, 1 };
    int       i;

    render_common (&s, pl);

    if (pl -> has_opt)
    {
        section (&s, "Optimize the ASM code");
        sb_puts (&s.b, "if \"%HAVE_OPT%\"==\"1\" (\r\n    ");
        preprocess_cmd (&s, pl);
        sb_puts (&s.b, "\r\n    if errorlevel 1 (\r\n        echo warning: the source did not preprocess -- skipping the optimized Opt build\r\n"
                       "    ) else (\r\n        \"%V32OPT%\" %V32OPT_FLAGS% ");
        put_bat (&s.b, pl -> asm_pre, 1);
        sb_puts (&s.b, " -o ");
        put_bat (&s.b, pl -> asm_opt, 1);
        sb_puts (&s.b, "\r\n        if errorlevel 1 (\r\n            echo warning: v32opt failed -- skipping the optimized Opt build\r\n"
                       "        ) else (\r\n            set OPT_OK=1\r\n        )\r\n    )\r\n)\r\n");
    }

    section (&s, "Assemble the ASM code");
    assemble_cmd (&s, pl, 0);
    sb_puts (&s.b, " || goto :failed\r\n");

    if (pl -> has_opt)
    {
        sb_puts (&s.b, "if \"%OPT_OK%\"==\"1\" (\r\n    ");
        assemble_cmd (&s, pl, 1);
        sb_puts (&s.b, "\r\n    if errorlevel 1 (\r\n        echo warning: the optimized code did not assemble -- skipping the optimized Opt build\r\n"
                       "        set OPT_OK=0\r\n    )\r\n)\r\n");
    }

    if (pl -> conv_in.n)
    {
        section (&s, "Convert the textures and sounds");

        for (i = 0; i < pl -> conv_in.n; i++)
        {
            sb_printf (&s.b, "\"%%%s%%\" ", pl -> conv_tool.v[i]);
            put_bat (&s.b, pl -> conv_in.v[i], 1);
            sb_puts (&s.b, " -o ");
            put_bat (&s.b, pl -> conv_out.v[i], 1);
            sb_puts (&s.b, " || goto :failed\r\n");
        }
    }

    section (&s, "Pack the ROM");
    sb_puts (&s.b, "\"%PACKROM%\" ");
    put_bat (&s.b, pl -> xml, 1);
    sb_puts (&s.b, " -o ");
    put_bat (&s.b, pl -> rom, 1);
    sb_puts (&s.b, " || goto :failed\r\n");

    if (pl -> has_opt)
    {
        sb_puts (&s.b, "if \"%OPT_OK%\"==\"1\" (\r\n    \"%PACKROM%\" ");
        put_bat (&s.b, pl -> xml_opt, 1);
        sb_puts (&s.b, " -o ");
        put_bat (&s.b, pl -> rom_opt, 1);
        sb_puts (&s.b, "\r\n    if errorlevel 1 echo warning: the optimized Opt cartridge could not be packed\r\n)\r\n");
    }

    sb_puts (&s.b, "goto :succeeded\r\n\r\n:failed\r\necho.\r\necho BUILD FAILED\r\nexit /b 1\r\n\r\n"
                   ":succeeded\r\necho.\r\necho BUILD SUCCESSFUL\r\nexit /b 0\r\n");

    return (sb_take (&s.b));
}

////////////////////////////////////////////////////////////////////////////////////////
//
// Writing
//
// Is this text one of ours?  The marker has to open a comment line ("# " in a shell script, "REM " in a batch file).
static int  has_marker (const char *text)
{
    const char  *p = text;

    while ((p = strstr (p, MARKER)) != NULL)
    {
        const char  *ls = p;

        while (ls > text && ls[-1] != '\n')
        {
            ls--;
        }

        if ((p - ls == 2 && strncmp (ls, "# ", 2) == 0) || (p - ls == 4 && strncasecmp (ls, "REM ", 4) == 0))
        {
            return (1);
        }

        p += strlen (MARKER);
    }

    return (0);
}

static char  *read_head (const char *path, size_t *n)
{
    FILE  *fp = fopen (path, "rb");
    char  *buf;

    if (fp == NULL)
    {
        return (NULL);
    }

    buf = xalloc (1 << 16);
    *n  = fread (buf, 1, (1 << 16) - 1, fp);
    buf[*n] = 0;
    fclose (fp);

    return (buf);
}

// -1: could not write it; 0: written, kept as it was, or left alone
static int  write_script (const char *dir, const char *name, const char *text, int executable)
{
    char    *path = join2 (dir, name);
    size_t   n = 0;
    char    *old = read_head (path, &n);
    char    *tmp;
    FILE    *fp;
    int      rc = 0;

    if (old != NULL && !has_marker (old))
    {
        fprintf (stderr, "v32as: warning: %s exists and was not generated by v32as; leaving it alone "
                         "(--no-build-scripts silences this)\n", path);
        free (old);
        free (path);
        return (0);
    }

    if (old != NULL && n == strlen (text) && memcmp (old, text, n) == 0)
    {
        free (old);
        free (path);
        return (0);                                  // unchanged: keep the file (and its time stamp)
    }

    free (old);

    // a new file under another name first, so that a copy of the old one that is running is not cut short
    tmp = xalloc (strlen (path) + 32);
    sprintf (tmp, "%s.tmp%ld", path, (long) getpid ());
    fp = fopen (tmp, "wb");

    if (fp == NULL)
    {
        fprintf (stderr, "v32as: warning: could not write the build script '%s': %s\n", path, strerror (errno));
        rc = -1;
    }
    else
    {
        int  bad = fwrite (text, 1, strlen (text), fp) != strlen (text);

        bad |= (fclose (fp) != 0);

        if (!bad)
        {
            chmod (tmp, executable ? 0755 : 0644);
#ifdef _WIN32
            remove (path);                           // (rename does not replace there)
#endif
            bad = (rename (tmp, path) != 0);
        }

        if (bad)
        {
            fprintf (stderr, "v32as: warning: could not write the build script '%s': %s\n", path, strerror (errno));
            remove (tmp);
            rc = -1;
        }
    }

    free (tmp);
    free (path);

    return (rc);
}

const char  *bs_bad_format (const char *formats)
{
    static char  word[64];
    const char  *p = formats;

    if (*p == 0)
    {
        return ("");
    }

    while (*p)
    {
        size_t  n = strcspn (p, ",");

        if (!((n == 2 && strncmp (p, "sh", 2) == 0) || (n == 3 && strncmp (p, "bat", 3) == 0)))
        {
            snprintf (word, sizeof (word), "%.*s", (int) (n < sizeof (word) ? n : sizeof (word) - 1), p);
            return (word);
        }

        p += n;

        if (*p == ',')
        {
            p++;
        }
    }

    return (NULL);
}

static int  wants (const char *formats, const char *fmt)
{
    size_t  m = strlen (fmt);
    const char  *p = formats;

    while (*p)
    {
        size_t  n = strcspn (p, ",");

        if (n == m && strncmp (p, fmt, m) == 0)
        {
            return (1);
        }

        p += n + (p[n] == ',');
    }

    return (0);
}

int  bs_emit_scripts (const bs_job_t *job)
{
    plan_t  pl;
    int     rc = 0;

    make_plan (&pl, job);

    if (wants (job -> formats, "sh"))
    {
        char  *t = render_sh (&pl);

        rc |= write_script (pl.dir, "Make.sh", t, 1);
        free (t);
    }

    if (wants (job -> formats, "bat"))
    {
        char  *t = render_bat (&pl);

        rc |= write_script (pl.dir, "Make.bat", t, 0);
        free (t);
    }

    plan_free (&pl);

    return (rc ? -1 : 0);
}
